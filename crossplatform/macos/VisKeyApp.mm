- (void)setupEventTap {
    CGEventMask mask = CGEventMaskBit(kCGEventKeyDown) |
                       CGEventMaskBit(kCGEventFlagsChanged) |
                       CGEventMaskBit(kCGEventLeftMouseDown) |
                       CGEventMaskBit(kCGEventRightMouseDown) |
                       CGEventMaskBit(kCGEventOtherMouseDown);

    self.eventTap = CGEventTapCreate(kCGHIDEventTap,
                                     kCGHeadInsertEventTap,
                                     kCGEventTapOptionDefault,
                                     mask,
                                     VisKeyEventCallback,
                                     NULL);
    if (!self.eventTap) {
        NSLog(@"[VisKey] Failed to create CGEventTap. Grant Accessibility permission in System Settings.");
        self.eventTapActive = NO;
        return;
    }

    self.eventTapActive = YES;
    self.runLoopSource = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, self.eventTap, 0);
    CFRunLoopAddSource(CFRunLoopGetCurrent(), self.runLoopSource, kCFRunLoopCommonModes);
    CGEventTapEnable(self.eventTap, true);
}

// Menu bar template images (design/icons/menubar-*.svg, rendered by crossplatform/branding/gen_branding.sh).
// "off" = event tap unavailable (missing Accessibility permission).
- (void)updateStatusIcon {
    NSString *imageName = !self.eventTapActive ? @"menubar-off"
                        : (self.vietnameseEnabled ? @"menubar-vi" : @"menubar-en");
    NSImage *image = [NSImage imageNamed:imageName];
    if (image) {
        [image setTemplate:YES];
        image.size = NSMakeSize(18, 18);
        self.statusItem.button.image = image;
        self.statusItem.button.title = @"";
    } else {
        self.statusItem.button.image = nil;
        self.statusItem.button.title = self.vietnameseEnabled ? @"VI" : @"EN";
    }
    NSMenuItem *toggleItem = [self.statusItem.menu itemWithTag:100];
    toggleItem.state = self.vietnameseEnabled ? NSControlStateValueOn : NSControlStateValueOff;
}

- (void)showAbout:(id)sender {
    NSMutableParagraphStyle *centered = [[NSMutableParagraphStyle alloc] init];
    centered.alignment = NSTextAlignmentCenter;
    NSColor *primary = [NSColor colorWithSRGBRed:0x30 / 255.0 green:0x44 / 255.0 blue:0xD6 / 255.0 alpha:1.0];

    NSMutableAttributedString *credits = [[NSMutableAttributedString alloc] init];
    [credits appendAttributedString:[[NSAttributedString alloc]
        initWithString:@"Gõ đúng ở mọi nơi.\n"
            attributes:@{NSFontAttributeName: [NSFont systemFontOfSize:13 weight:NSFontWeightSemibold],
                         NSForegroundColorAttributeName: primary,
                         NSParagraphStyleAttributeName: centered}]];
    [credits appendAttributedString:[[NSAttributedString alloc]
        initWithString:@"by 1VISION · Dựa trên OpenKey của Mai Vũ Tuyên · GPL-3.0"
            attributes:@{NSFontAttributeName: [NSFont systemFontOfSize:11],
                         NSForegroundColorAttributeName: [NSColor secondaryLabelColor],
                         NSParagraphStyleAttributeName: centered}]];

    NSString *version = [NSBundle.mainBundle objectForInfoDictionaryKey:@"CFBundleShortVersionString"] ?: @"1.0.0";
    [NSApp activateIgnoringOtherApps:YES];
    [NSApp orderFrontStandardAboutPanelWithOptions:@{
        NSAboutPanelOptionApplicationName: @"VisKey",
        NSAboutPanelOptionApplicationVersion: version,
        NSAboutPanelOptionVersion: @"",
        NSAboutPanelOptionCredits: credits
    }];
}

- (void)toggleVietnameseMode:(id)sender {
    self.vietnameseEnabled = !self.vietnameseEnabled;
    gEngine.reset();
    NSString *bundleId = NSWorkspace.sharedWorkspace.frontmostApplication.bundleIdentifier;
    if (self.smartPerAppMode && bundleId) {
        self.appModes[bundleId] = @(self.vietnameseEnabled);
    }
    [self updateStatusIcon];
}

- (void)selectTelex:(NSMenuItem *)sender {
    gEngine.config().input_method = "telex";
    gEngine.reset();
    sender.state = NSControlStateValueOn;
    [[self.statusItem.menu itemWithTag:202] setState:NSControlStateValueOff];
}

- (void)selectVNI:(NSMenuItem *)sender {
    gEngine.config().input_method = "vni";
    gEngine.reset();
    sender.state = NSControlStateValueOn;
    [[self.statusItem.menu itemWithTag:201] setState:NSControlStateValueOff];
}

- (void)toggleOrthography:(NSMenuItem *)sender {
    gEngine.config().modern_orthography = !gEngine.config().modern_orthography;
    sender.state = gEngine.config().modern_orthography ? NSControlStateValueOn : NSControlStateValueOff;
}

- (void)toggleAutoRestore:(NSMenuItem *)sender {
    gEngine.config().auto_restore_english = !gEngine.config().auto_restore_english;
    sender.state = gEngine.config().auto_restore_english ? NSControlStateValueOn : NSControlStateValueOff;
}

- (void)toggleAutocompleteFix:(NSMenuItem *)sender {
    gEngine.config().fix_autocomplete = !gEngine.config().fix_autocomplete;
    sender.state = gEngine.config().fix_autocomplete ? NSControlStateValueOn : NSControlStateValueOff;
}

- (void)togglePerAppMode:(NSMenuItem *)sender {
    self.smartPerAppMode = !self.smartPerAppMode;
    sender.state = self.smartPerAppMode ? NSControlStateValueOn : NSControlStateValueOff;
}

- (void)toggleMacros:(NSMenuItem *)sender {
    bool next = !gEngine.config().enable_macros;
    gEngine.config().enable_macros = next;
    gEngine.config().quick_telex = next;
    sender.state = next ? NSControlStateValueOn : NSControlStateValueOff;
}

- (void)handleActiveAppChanged:(NSNotification *)notification {
    gEngine.reset();
    if (!self.smartPerAppMode) return;

    NSRunningApplication *app = notification.userInfo[NSWorkspaceApplicationKey];
    NSString *bundleId = app.bundleIdentifier;
    if (!bundleId) return;

    NSNumber *savedMode = self.appModes[bundleId];
    if (savedMode != nil) {
        self.vietnameseEnabled = savedMode.boolValue;
    } else if ([self.defaultEnglishBundles containsObject:bundleId]) {
        self.vietnameseEnabled = NO;
        self.appModes[bundleId] = @NO;
    }
    [self updateStatusIcon];
}

@end

int main(int argc, const char * argv[]) {
    @autoreleasepool {
        NSApplication *app = [NSApplication sharedApplication];
        [app setActivationPolicy:NSApplicationActivationPolicyAccessory];
        VisKeyController *delegate = [[VisKeyController alloc] init];
        app.delegate = delegate;
        [app run];
    }
    return 0;
}
